# SATELLITES — DETAIL
# ---------------------------------------------------------

@router.get("/satellites/{norad_cat_id}")
def get_satellite(norad_cat_id: int):

    conn = get_connection()
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()

    cursor.execute(
        """
        SELECT *
        FROM satellites
        WHERE norad_cat_id = ?
        """,
        (norad_cat_id,)
    )

    row = cursor.fetchone()

    conn.close()

    if row is None:
        raise HTTPException(
            status_code=404,
            detail="Satellite not found"
        )

    return dict(row)


